
public class programa06 {
    public static void main(String [] args ) { 

        int x, y; 
        x = 10;
        y = 5;
        System.out.printf("Maior, %d > %d = %s%n", x, y, x > y);
        System.out.printf("Menor, %d < %d = %s%n", x, y, x < y);
        System.out.printf("Maior ou igual, %d >= %d = %s%n", x, y, x >= y);
        System.out.printf("Menor ou igual, %d <= %d = %s%n", x, y, x <= y);
        System.out.printf("Diferença, %d != %d = %s%n", x, y, x != y);
    }
}